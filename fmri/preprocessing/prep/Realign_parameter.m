function [Max_Translation, Max_Rotation]=motion_curve_plot(rpfilepath,Pictures_path)

data=load(rpfilepath);

Max_HeadMotion=max(abs(data));
Max_HeadMotion(4:6)=Max_HeadMotion(4:6)*180/pi;

Max_Translation=max(Max_HeadMotion(1:3));
Max_Rotation=max(Max_HeadMotion(4:6));

h1=figure('Visible', 'off');
plot(data(:,1),'b','LineWidth',1.5);
hold on
plot(data(:,2),'g','LineWidth',1.5);
hold on
plot(data(:,3),'r','LineWidth',1.5);
grid on
title('Translation')
xlabel('Repetition')
ylabel('mm')
legend('X','Y','Z')
set(gca,'xlim',[0 size(data,1)]);
hold off

h2=figure('Visible', 'off');
plot(data(:,4)*180/pi,'b','LineWidth',1.5);
hold on
plot(data(:,5)*180/pi,'g','LineWidth',1.5);
hold on
plot(data(:,6)*180/pi,'r','LineWidth',1.5);
grid on
title('Rotation')
xlabel('Repetition')
ylabel('degree')
legend('Pitch','Yaw','Roll')
set(gca,'xlim',[0 size(data,1)]);
hold off

motion_name1=strcat(Pictures_path,'\Translation.tif');
motion_name2=strcat(Pictures_path,'\Rotation.tif');

saveas(h1,motion_name1);
saveas(h2,motion_name2);

close(h1);
close(h2);
end

