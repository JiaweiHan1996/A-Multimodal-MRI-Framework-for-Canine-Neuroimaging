function PP = Realign_parameter(PP)
%% update: 20251107
% ProcessMotionParameters - Process motion parameters for all subjects

fprintf(['\nRealign Parameter Calculate Starting    ||    ' spm('time') '\n']);

DataList = PP.DataList;

% Create main RP and QC directories
RP_Path = fullfile(DataList.dataroot_path, 'RealignParameter');
QC_Path = fullfile(DataList.dataroot_path, 'QC');

% Remove and recreate main directories
if exist(RP_Path, 'dir')
    rmdir(RP_Path, 's');
end
mkdir(RP_Path);

if exist(QC_Path, 'dir')
    rmdir(QC_Path, 's');
end
mkdir(QC_Path);

% Initialize RMS structure
RMS = struct();

for i = 1:length(PP.RefEcho_Para.RefFun_list)
    % Generate input parameters with subject subfolders
    Fun_src_Path = fileparts(PP.RefEcho_Para.RefFun_list{i});
    sub = DataList.Sublist{PP.RefEcho+PP.Enum * (i-1)};
    RP_dst_Path = fullfile(RP_Path, sub);
    QC_dst_Path = fullfile(QC_Path, sub);

    % Remove and recreate subject directories
    if exist(RP_dst_Path, 'dir')
        rmdir(RP_dst_Path, 's');
    end
    mkdir(RP_dst_Path);
    
    if exist(QC_dst_Path, 'dir')
        rmdir(QC_dst_Path, 's');
    end
    mkdir(QC_dst_Path);
    
    % Process motion parameters
    [Max_Translation, Max_Rotation, Max_displacement] = rm_file_and_calc_rms(Fun_src_Path, RP_dst_Path, QC_dst_Path);
    
    % Store results
    RMS(i).SID = sub;
    RMS(i).MAX = [Max_Translation, Max_Rotation, Max_displacement];
    clear Max_Translation Max_Rotation Max_displacement sub
end

% Generate subjects_remove_criteria.txt
[maxMotion_txtPath] = maxMotionText(RMS, QC_Path);

% Update PP structure
PP.RP_Path = RP_Path;
PP.QC_Path = QC_Path;

fprintf(['\nRealign Parameter Generated    ||    ' spm('time') '\n']);
end

function [Max_Translation, Max_Rotation, Max_displacement] = rm_file_and_calc_rms(Fun_src_Path, RP_dst_Path, QC_dst_Path)
    % ---------- Move Some Files ----------
    [a,b,~]=fileparts(RP_dst_Path);
    if contains(b, 'Echo', 'IgnoreCase', true)
        RP_dst_Path = a;
    end
    movefile([Fun_src_Path filesep 'mean*'], RP_dst_Path);
    movefile([Fun_src_Path filesep 'rp*'], RP_dst_Path);
    movefile([Fun_src_Path filesep '*.mat'], RP_dst_Path);

    % ---------- Calc. rms ----------
    DirList4RegExp = dir([RP_dst_Path filesep 'rp*']);
    rpfilepath = [RP_dst_Path filesep DirList4RegExp.name]; clear DirList4RegExp

    Ref_name = dir([RP_dst_Path filesep 'mean*']);
    Ref_Path = [RP_dst_Path filesep Ref_name.name]; clear Ref_name

    [Max_Translation, Max_Rotation] = motion_curve_plot(rpfilepath, QC_dst_Path);
    
    [rel_rms, abs_rms] = rp_y_FD_Jenkinson(rpfilepath, Ref_Path);
    rms = [rel_rms, abs_rms];
    save([RP_dst_Path filesep 'rms' '.txt'], 'rms', '-ASCII', '-DOUBLE','-TABS');

    rmsfilepath = [RP_dst_Path filesep 'rms.txt'];
    [Max_displacement] = rms_curve_plot(rmsfilepath, QC_dst_Path);

end

