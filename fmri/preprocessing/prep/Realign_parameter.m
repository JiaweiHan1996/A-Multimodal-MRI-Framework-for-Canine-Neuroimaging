function [Max_displacement]=rms_curve_plot(rmsfilepath,Pictures_path)

data=load(rmsfilepath);

Max_displacement=max(abs(data(:,2)));

h=figure('Visible', 'off');
plot(data(:,1),'b','LineWidth',1.5);
hold on
plot(data(:,2),'g','LineWidth',1.5);

grid on
title('Displacement')
xlabel('Repetition')
ylabel('mm')
legend('relative','absolute');
set(gca,'xlim',[0 size(data,1)]);

motion_name=strcat(Pictures_path,'\rms.tif');
saveas(h,motion_name);

close(h);
end

